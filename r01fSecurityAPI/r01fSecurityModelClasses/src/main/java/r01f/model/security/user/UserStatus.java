package r01f.model.security.user;

import lombok.RequiredArgsConstructor;
import lombok.experimental.Accessors;
import r01f.enums.EnumExtended;

@Accessors(prefix="_")
@RequiredArgsConstructor
public enum UserStatus
 implements EnumExtended<UserStatus> {
/////////////////////////////////////////////////////////////////////////////////////////
//
/////////////////////////////////////////////////////////////////////////////////////////
	ACTIVE,
	PENDING_ADMIN_APROVAL,
	PENDING_USER_DATA_COMPLETION,
	INACTIVE;
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	public static final boolean canBe(final String name) {
		return EnumExtended.canBeFromName(name,UserStatus.class);
	}
}
