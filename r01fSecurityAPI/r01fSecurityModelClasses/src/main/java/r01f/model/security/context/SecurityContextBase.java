import r01f.util.types.collections.CollectionUtils;
import r01f.util.types.collections.Lists;

/**
 * {@link SecurityContext} implementation
 */
@Accessors(prefix="_")
public abstract class SecurityContextBase<SELF_TYPE extends SecurityContextBase<SELF_TYPE>>
           implements SecurityContext {

	private static final long serialVersionUID = 6313898883935383799L;
/////////////////////////////////////////////////////////////////////////////////////////
//  FIELDS
/////////////////////////////////////////////////////////////////////////////////////////
////////// --- CREATE DATE
	/**
	 * The date this [security context] was created
	 */
	@MarshallField(as="createdAt",
				   whenXml=@MarshallFieldAsXml(attr=true))
	@Getter @Setter protected Instant _createdAt;
	
////////// --- VALIDATION
	/**
	 * Is the security context still valid
	 */
	@MarshallField(as="valid",
				   whenXml=@MarshallFieldAsXml(attr=true))
	@Getter @Setter protected boolean _valid;
	/**
	 * A signed token that proves that this [security context] was generated by a legitimate system
	 */
	@MarshallField(as="validationToken",escape=true)
	@Getter @Setter protected SecurityToken _validationToken;
	
////////// --- TENANT	
	/**
	 * Tenant id (tenatA, tenantB, ...)
	 * Allows the database and file system data to be partitioned by this value
	 */
	@MarshallField(as="tenantId",
				   whenXml=@MarshallFieldAsXml(attr=true))
	@Getter @Setter protected TenantID _tenantId; 	// TODO the tenant id should come with the authentication data (ie xlnets)
	
////////// --- SECURITY PRINCIPAL
	/**
	 * The security principal (person, process, device, ...)
	 */
	@MarshallField(as="securityPrincipal")
	@Getter @Setter protected IsSecurityPrincipal _securityPrincipal;
	
	@MarshallField(as="impersonatingSecurityPrincipalOid",
				   whenXml=@MarshallFieldAsXml(attr=true))
	@Getter @Setter protected SecurityPrincipalOID _impersonatingSecurityPrincipalOid;	// if the security context is impersonating another security principal, this field contains the impersonated security principal oid
	
////////// --- LOGIN & LOGOUT urls 
	/**
	 * The login page url
	 */
	@MarshallField(as="loginUrl")
	@Getter @Setter protected Url _loginUrl;
	/**
	 * The logout url (usually it's something like: /{web-app}/logout
	 */
	@MarshallField(as="logoutUrl")
	@Getter @Setter protected Url _logoutUrl;
	
////////// --- AUTHORIZATION DATA
	/**
	 * The security principal system-wide roles (if any)
	 */
	@Getter @Setter protected SecurityPrincipalSystemWideRoles _systemWideRoles;
	
////////// --- RUNTIME DATA	
	/**
	 * A convenient collection of run-time data
	 * This data is NOT serialized when the object is persisted!
	 */
	@MarshallIgnoredField	// DO NOT SERIALIZE
	@Getter protected transient Collection<SecurityContextRuntimeData<?>> _runtimeData;

	private record SecurityContextRuntimeData<T>(String id,
									  			 T data) {
		static Predicate<SecurityContextRuntimeData<?>> createRuntimeDataByIdFilter(final String id) {
			return data -> data.data() != null
						&& id.equals(data.id());
		}
	}
/////////////////////////////////////////////////////////////////////////////////////////
//  CONSTRUCTOR
/////////////////////////////////////////////////////////////////////////////////////////
	protected SecurityContextBase(final IsSecurityPrincipal securityPrincipal) {
		this(securityPrincipal, 
			 TenantID.DEFAULT);
	}
	protected SecurityContextBase(final IsSecurityPrincipal securityPrincipal,
								  final TenantID tenantId) {
		if (securityPrincipal == null) throw new IllegalArgumentException("The [security principal] is mandatory");
		
		_createdAt = Instant.now();
		_securityPrincipal = securityPrincipal;
		_tenantId = tenantId != null ? tenantId
									 : TenantID.DEFAULT;
	}
	protected SecurityContextBase(final SecurityPrincipalForSystem securityPrincipal) {
		this((IsSecurityPrincipal)securityPrincipal);
	}
	protected SecurityContextBase(final SecurityPrincipalForClientApp securityPrincipal) {
		this((IsSecurityPrincipal)securityPrincipal);
	}
/////////////////////////////////////////////////////////////////////////////////////////
//  VALIDATION
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public void invalidate() {
		_valid = false;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	SECURITY PRINCIPAL
/////////////////////////////////////////////////////////////////////////////////////////
////////// --- SYSTEM	
	@Override
	public boolean isForSystemSecurityPrincipal() {
		return _securityPrincipal instanceof SecurityPrincipalForSystem;
	}
	
////////// --- PERSON	
	@Override
	public boolean isForPersonSecurityPrincipal() {
		return _securityPrincipal instanceof SecurityPrincipalForPersonBase;
	}
	@Override @SuppressWarnings("unchecked")
	public <D extends IsSecurityPrincipalDataForPerson,S extends SecurityContextForPerson<D>> S asForPersonSecurityPrincipal(final Class<S> personType) {
		return (S)new SecurityContextForPersonImpl<>(this);
	}
	public class SecurityContextForPersonImpl<D extends IsSecurityPrincipalDataForPerson>
		 extends SecurityContextWrapperBase
 	  implements SecurityContextForPerson<D> {
		
		private static final long serialVersionUID = 7637935313556110111L;
		
		public SecurityContextForPersonImpl(final SecurityContext wrappedSecurityContext) {
			super(wrappedSecurityContext);
		}
		@Override @SuppressWarnings("unchecked")
		public <D2 extends IsSecurityPrincipalDataForPerson,S extends SecurityContextForPerson<D2>> S asForPersonSecurityPrincipal(final Class<S> type) {
			return (S)this;
		}
		@Override
		public D getPersonData() {
			return _securityPrincipal.as(new TypeToken<SecurityPrincipalForPersonBase<D,?>>() {})
									 .getPersonData();
		}
	}
	
////////// --- CLIENT-APP	
	@Override
	public boolean isForClientAppSecurityPrincipal() {
		return _securityPrincipal instanceof SecurityPrincipalForClientApp;
	}
	@Override @SuppressWarnings("unchecked")
	public <S extends SecurityContextForClientApp> S asForClientAppSecurityPrincipal(final Class<S> type) {
		return (S)new SecurityContextForClientAppImpl(this);
	}
	public class SecurityContextForClientAppImpl
		 extends SecurityContextWrapperBase
 	  implements SecurityContextForClientApp {
		
		private static final long serialVersionUID = 5722836902896240272L;
		
		public SecurityContextForClientAppImpl(final SecurityContext wrappedSecurityContext) {
			super(wrappedSecurityContext);
		}
		@Override @SuppressWarnings("unchecked")
		public <S extends SecurityContextForClientApp> S asForClientAppSecurityPrincipal(final Class<S> type) {
			return (S)this;
		}
		
		@Override
		public AppCode getAppCode() {
			return _securityPrincipal.as(SecurityPrincipalForClientApp.class)
									 .getAppCode();
		}
		@Override
		public AppComponent getAppComponent() {
			return _securityPrincipal.as(SecurityPrincipalForClientApp.class)
									 .getAppComponent();
		}
	}
////////// --- SECURITY CONTEXT WRAPPER	
	@RequiredArgsConstructor(access=AccessLevel.PRIVATE)
	public abstract class SecurityContextWrapperBase
			   implements SecurityContext {

		private static final long serialVersionUID = 8089044113116260225L;
		
		////////// --- FIELDS
		private final SecurityContext _wrappedSecurityContext;

		////////// --- DELEGATED 
		@Override
		public Instant getCreatedAt() {
			return _wrappedSecurityContext.getCreatedAt();
		}
		@Override
		public boolean isValid() {
			return _wrappedSecurityContext.isValid();
		}
		@Override
		public void invalidate() {
			_wrappedSecurityContext.invalidate();
		}
		@Override
		public SecurityToken getValidationToken() {
			return _wrappedSecurityContext.getValidationToken();
		}
		@Override
		public TenantID getTenantId() {
			return _wrappedSecurityContext.getTenantId();
		}
		////////// --- SECURITY PRINCIPAL
		@Override
		public IsSecurityPrincipal getSecurityPrincipal() {
			return _wrappedSecurityContext.getSecurityPrincipal();
		}
		@Override
		public boolean isForSystemSecurityPrincipal() {
			return _wrappedSecurityContext.isForSystemSecurityPrincipal();
		}
		@Override
		public boolean isForPersonSecurityPrincipal() {
			return _wrappedSecurityContext.isForPersonSecurityPrincipal();
		}
		@Override
		public <D extends IsSecurityPrincipalDataForPerson,S extends SecurityContextForPerson<D>> S asForPersonSecurityPrincipal(final Class<S> personType) {
			throw new ClassCastException("The [security context] is not for a [person] [security principal]");
		}
		@Override
		public <S extends SecurityContextForClientApp> S asForClientAppSecurityPrincipal(final Class<S> type) {
			throw new ClassCastException("The [security context] is not for a [client app] [security principal]");
		}
		@Override
		public boolean isForClientAppSecurityPrincipal() {
			return _wrappedSecurityContext.isForClientAppSecurityPrincipal();
		}
		////////// --- IMPERSONATION
		@Override
		public SecurityPrincipalOID getImpersonatingSecurityPrincipalOid() {
			return _wrappedSecurityContext.getImpersonatingSecurityPrincipalOid();
		}
		@Override
		public void setImpersonatingSecurityPrincipalOid(final SecurityPrincipalOID impersonatedSecurityPrincipalOid) {
			_wrappedSecurityContext.setImpersonatingSecurityPrincipalOid(impersonatedSecurityPrincipalOid);
		}
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	RUNTIME DATA
/////////////////////////////////////////////////////////////////////////////////////////	
	@SuppressWarnings("unchecked")
	public <T> SELF_TYPE addRuntimeData(final SecurityContextRuntimeData<T> runTimeData) {
		this.removeRuntimeDataWithId(runTimeData.id());	// ensure there DOES NOT exist two entries with the same ID

		if (_runtimeData == null) _runtimeData = Lists.newArrayList();
		_runtimeData.add(runTimeData);
		return (SELF_TYPE)this;
	}
	public <T> SELF_TYPE addRuntimeData(final String id,final T runTimeData) {
		return this.addRuntimeData(new SecurityContextRuntimeData<>(id,runTimeData));
	}
	public boolean removeRuntimeDataWithId(final String id) {
		if (!this.hasRuntimeData() || !this.containsRuntimeDataWithId(id)) return false;

		SecurityContextRuntimeData<?> prev = _getRuntimeDataWithId(id);
		if (prev != null) _runtimeData.remove(prev);
		return prev != null;
	}
	public boolean hasRuntimeData() {
		return CollectionUtils.hasData(_runtimeData);
	}
	public boolean containsRuntimeDataWithId(final String id) {
		return this.getRuntimeDataWithId(id) != null;
	}
	@SuppressWarnings("unchecked")
	public <T> T getRuntimeDataWithId(final String id) {
		if (id == null || CollectionUtils.isNullOrEmpty(_runtimeData)) return null;
		return _runtimeData.stream()
						   .filter(SecurityContextRuntimeData.createRuntimeDataByIdFilter(id))
						   .map(data -> (T)data.data())
						   .findFirst().orElse(null);
	}
	private SecurityContextRuntimeData<?> _getRuntimeDataWithId(final String id) {
		if (id == null || CollectionUtils.isNullOrEmpty(_runtimeData)) return null;
		return _runtimeData.stream()
						   .filter(SecurityContextRuntimeData.createRuntimeDataByIdFilter(id))
						   .findFirst().orElse(null);
	}
	public void copyRuntimeDataFrom(final SELF_TYPE other) {
		if (!other.hasRuntimeData()) return;

		Collection<SecurityContextRuntimeData<?>> otherRuntimeData = other.getRuntimeData();
		for (SecurityContextRuntimeData<?> otherRuntimeDataItem : otherRuntimeData) {
			this.addRuntimeData(otherRuntimeDataItem);
		}
	}
}
