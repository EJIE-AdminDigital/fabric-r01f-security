package r01f.model.security.context;


import java.time.Instant;
import java.util.Optional;

import com.google.common.reflect.TypeToken;

import lombok.Getter;
import lombok.Setter;
import lombok.experimental.Accessors;
import r01f.guids.CommonOIDs.AppCode;
import r01f.guids.CommonOIDs.AppComponent;
import r01f.guids.CommonOIDs.TenantID;
import r01f.guids.OID;
import r01f.locale.Language;
import r01f.model.security.user.User;
import r01f.model.security.user.UserRoleInModule;
import r01f.objectstreamer.annotations.MarshallField;
import r01f.objectstreamer.annotations.MarshallField.MarshallFieldAsXml;
import r01f.patterns.FactoryFrom;
import r01f.securitycontext.SecurityContext;
import r01f.securitycontext.SecurityContextAuthenticatedActor;
import r01f.securitycontext.SecurityContextForApiKey;
import r01f.securitycontext.SecurityContextForApp;
import r01f.securitycontext.SecurityContextForRegisteredDevice;
import r01f.securitycontext.SecurityContextForUser;
import r01f.securitycontext.SecurityIDS.LoginID;
import r01f.securitycontext.SecurityIDS.SecurityProviderID;
import r01f.securitycontext.SecurityIDS.SecurityToken;
import r01f.securitycontext.SecurityIDS.UserRole;
import r01f.securitycontext.SecurityOIDs.LoginOID;
import r01f.securitycontext.SecurityOIDs.UserOID;
import r01f.types.AppVersion;
import r01f.types.url.Url;
import r01f.util.types.collections.CollectionUtils;

/**
 * {@link SecurityContext} implementation
 */
@Accessors(prefix="_")
public abstract class SecurityContextBase
           implements SecurityContext {

	private static final long serialVersionUID = 6313898883935383799L;
/////////////////////////////////////////////////////////////////////////////////////////
//  FIELDS
/////////////////////////////////////////////////////////////////////////////////////////
	/**
	 * Tenant id (tenatA, tenantB, ...)
	 * Allows the database and file system data to be partitioned by this value
	 */
	@MarshallField(as="tenantId",
				   whenXml=@MarshallFieldAsXml(attr=true))
	@Getter @Setter protected TenantID _tenantId; 	// TODO the tenant id should come with the authentication data (ie xlnets)
	/**
	 * The date this user context was created
	 */
	@MarshallField(as="createDate",
				   whenXml=@MarshallFieldAsXml(attr=true))
	@Getter @Setter protected Instant _createDate;
	/**
	 * The authenticated actor
	 */
	@MarshallField(as="authActor",
				   whenXml=@MarshallFieldAsXml(attr=true))
	@Getter @Setter protected SecurityContextAuthenticatedActor _authenticatedActor;
	/**
	 * A security token (a jwt, some signed token, etc)
	 * Usually this is used at MASTER security contexts that SHOULD ONLY be created by a legitimated system
	 * (NOT anyone can generate a MASTER security context)
	 * ... in order to ensure that this security context is a legitimate one, the provider that
	 * 	   generates it, signs a token with a private key that only that legitimate provider knows
	 * ... when the token is validated, the signed token can be checked to ensure it was generated by a
	 *     legitimate system
	 */
	@MarshallField(as="securityToken",escape=true)
	@Getter @Setter protected SecurityToken _securityToken;
	/**
	 * The login page url
	 */
	@MarshallField(as="loginUrl")
	@Getter @Setter protected Url _loginUrl;
	/**
	 * The logout url (usually it's something like: /{web-app}/logout
	 */
	@MarshallField(as="logoutUrl")
	@Getter @Setter protected Url _logoutUrl;
	/**
	 * Is the security context still valid
	 */
	@MarshallField(as="valid",
				   whenXml=@MarshallFieldAsXml(attr=true))
	@Getter @Setter protected boolean _valid;
/////////////////////////////////////////////////////////////////////////////////////////
//  CONSTRUCTOR
/////////////////////////////////////////////////////////////////////////////////////////
	protected SecurityContextBase() {
		_createDate = Instant.now();
	}
////////// Auth actor
	public SecurityContextBase(final SecurityContextAuthenticatedActor authActor) {
		this(authActor,
			 TenantID.DEFAULT);
	}
	public SecurityContextBase(final SecurityContextAuthenticatedActor authActor,
						   	   final TenantID tenantId) {
		this(authActor,
			 null,	// no token
			 tenantId);
	}
	public SecurityContextBase(final SecurityContextAuthenticatedActor authActor,
							   final SecurityToken securityToken) {
		this(authActor,
			 securityToken,
			 TenantID.DEFAULT);
	}
	public SecurityContextBase(final SecurityContextAuthenticatedActor authActor,
							   final SecurityToken securityToken,
							   final TenantID tenantId) {
		_createDate = Instant.now();
		_authenticatedActor = authActor;
		_tenantId = tenantId;
		_securityToken = securityToken;
	}
////////// Security token
	public SecurityContextBase(final SecurityToken securityToken) {
		this(securityToken,
			 TenantID.DEFAULT);
	}
	public SecurityContextBase(final SecurityToken securityToken,
							   final TenantID tenantId) {
		this();
		_securityToken = securityToken;
		_tenantId = tenantId;
		_createDate = Instant.now();
	}
/////////////////////////////////////////////////////////////////////////////////////////
//  METHODS
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public LoginID getLoginId() {
		return _authenticatedActor.getLoginId();
	}
	@Override
	public SecurityProviderID getSecurityProviderId() {
		return _authenticatedActor.getSecurityProviderId();
	}
	@Override
	public void invalidate() {
		_valid = false;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	ROLES
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public boolean userHasSystemWideRoleIn(final AppComponent appComp,
									   	   final UserRole role) {
		UserRole userRole = this.getUserSystemWideRoleIn(appComp);
		return userRole != null
			&& userRole.is(role);
	}
	@Override
	public boolean userHasAnySystemWideRoleIn(final AppComponent module) {
		if (!this.isForUser()) throw new UnsupportedOperationException("only USER [security context] has system-wide roles");
		User user = this.getUser(User.class);	// any user type
		return user.hasAnyUserSystemWideRoleIn(module);
	}
	@Override
	public UserRole getUserSystemWideRoleIn(final AppComponent module) {
		UserRoleInModule roleInModule = _userSystemWideUserRoleIn(module);
		return roleInModule != null ? roleInModule.getRole() : null;
	}
	private UserRoleInModule _userSystemWideUserRoleIn(final AppComponent module) {
		if (!this.isForUser()) throw new UnsupportedOperationException("only USER [security context] has system-wide roles");
		User user = this.getUser(User.class);	// any user type
		return CollectionUtils.hasData(user.getUserSystemWideRoles()) ? user.getUserSystemWideRoles()
																			.stream()
																			.filter(role -> role.getAppComponent().is(module))
																			.findFirst().orElse(null)
																	  : null;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	USER
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public boolean isForUser() {
		return _authenticatedActor.isForUser();
	}
	@Override
	public SecurityContextForUser asForUser() {
		if (!this.isForUser()) throw new IllegalStateException("The [security context] is NOT a [user] [security context]!");
		return new SecurityContextForUser() {
						@Override
						public UserOID getUserOid() {
							User user =  _authenticatedActor.as(SecurityContextAuthenticatedActorForUser.class)
															.getUser();
							return user.getOid();
						}
						@Override
						public Optional<Language> getPrefLang() {
							User user =  _authenticatedActor.as(SecurityContextAuthenticatedActorForUser.class)
															.getUser();
							return Optional.ofNullable(user.getPrefLang());
						}
						@Override
						public String getDisplayName() {
							User user =  _authenticatedActor.as(SecurityContextAuthenticatedActorForUser.class)
															.getUser();
							return user.getDisplayName();
						}
			   };
	}
	public <U extends User> U getUser(final Class<U> userType) {
		if (!this.isForUser()) throw new UnsupportedOperationException("only USER [security context] has user data");
		U user = this.getAuthenticatedActorAsForUser(userType)
					 .getUser();
		return user;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	API KEY
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public SecurityContextForApiKey asForApiKey() {
		if (!this.isForApiKey()) throw new IllegalStateException("The [security context] is NOT an [api key] [security context]!");
		return new SecurityContextForApiKey() {
						@Override
						public LoginOID getApiKeyOid() {
							return _authenticatedActor.as(SecurityContextAuthenticatedActorForApiKey.class)
													  .getApiKeyOid();
						}
						@Override
						public AppVersion getApiKeyVersion() {
							return _authenticatedActor.as(SecurityContextAuthenticatedActorForApiKey.class)
													  .getApiKeyVersion();
						}
			   };
	}
	@Override
	public boolean isForApiKey() {
		return _authenticatedActor.isForApiKey();
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	APP
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public SecurityContextForApp asForApp() {
		if (!this.isForApp()) throw new IllegalStateException("The [security context] is NOT an [app] [security context]!");
		return new SecurityContextForApp() {
						@Override
						public AppCode getAppCode() {
							return _authenticatedActor.as(SecurityContextAuthenticatedActorForApp.class)
													  .getAppCode();
						}
			   };
	}
	@Override
	public boolean isForApp() {
		return _authenticatedActor.isForApp();
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	REGISTERED DEVICE
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public <O extends OID> SecurityContextForRegisteredDevice<O> asForRegisteredDevice(final FactoryFrom<LoginID,O> deviceOidFactory) {
		if (!this.isForRegisteredDevice()) throw new IllegalStateException("The [security context] is NOT a [registered device] [security context]!!");
		return new SecurityContextForRegisteredDevice<>() {
						@Override @SuppressWarnings("unchecked")
						public O getDeviceOid() {
							return (O)_authenticatedActor.as(SecurityContextAuthenticatedActorForRegisteredDevice.class)
													     .getDeviceOidUsing(deviceOidFactory);
						}
			   };
	}
	@Override
	public boolean isForRegisteredDevice() {
		return _authenticatedActor.isForRegisteredDevice();
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	SYSTEM
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public boolean isForSystem() {
		return _authenticatedActor.isForSystem();
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	LANGUAGE
/////////////////////////////////////////////////////////////////////////////////////////
	public Language getPrefLang() {
		if (!this.isForUser()) throw new UnsupportedOperationException("only USER [security context] has pref lang");
		return this.getPrefLangOrDefault(Language.DEFAULT);
	}
	public Language getPrefLangOrDefault(final Language def) {
		if (!this.isForUser()) throw new UnsupportedOperationException("only USER [security context] has pref lang");
		User user = this.getAuthenticatedActorAsForUser(User.class)
						.getUser();
		return user != null
			&& user.getPrefLang() != null
						? user.getPrefLang()
						: def;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//
/////////////////////////////////////////////////////////////////////////////////////////
	@Override @SuppressWarnings("unchecked")
	public <CTX extends SecurityContext> CTX as(final Class<CTX> type) {
		return (CTX)this;
	}
	@Override @SuppressWarnings("unchecked")
	public <A extends SecurityContextAuthenticatedActor> A getAuthenticatedActorAs(final Class<A> actorType) {
		return (A)_authenticatedActor;
	}
	@Override @SuppressWarnings("unchecked")
	public <A extends SecurityContextAuthenticatedActor> A getAuthenticatedActorAs(final TypeToken<A> actorType) {
		return (A)_authenticatedActor;
	}
	@SuppressWarnings({ "serial" })
	public <U extends User> SecurityContextAuthenticatedActorForUser<U> getAuthenticatedActorAsForUser(final Class<U> userType) {
		if (!this.getAuthenticatedActor().isForUser()) throw new IllegalStateException("The security context is NOT a USER security context!!");
		return this.getAuthenticatedActorAs(new TypeToken<SecurityContextAuthenticatedActorForUser<U>>() { /* nothing */ });
	}
}
