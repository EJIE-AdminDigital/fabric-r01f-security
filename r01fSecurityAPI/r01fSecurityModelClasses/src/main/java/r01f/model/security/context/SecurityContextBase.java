package r01f.model.security.context;


import java.time.Instant;
import java.util.Collection;
import java.util.function.Predicate;

import com.google.common.reflect.TypeToken;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.RequiredArgsConstructor;
import lombok.Setter;
import lombok.experimental.Accessors;
import r01f.model.security.IsSecurityPrincipal;
import r01f.model.security.IsSecurityPrincipalDataForPerson;
import r01f.model.security.principal.SecurityPrincipalForClientApp;
import r01f.model.security.principal.SecurityPrincipalForPersonBase;
import r01f.model.security.principal.SecurityPrincipalForSystem;
import r01f.model.security.principal.SecurityPrincipalSystemWideRoles;
import r01f.objectstreamer.annotations.MarshallField;
import r01f.objectstreamer.annotations.MarshallField.MarshallFieldAsXml;
import r01f.objectstreamer.annotations.MarshallIgnoredField;
import r01f.oids.CommonOIDs.AppCode;
import r01f.oids.CommonOIDs.AppComponent;
import r01f.oids.CommonOIDs.TenantID;
import r01f.oids.SecurityIDs.SecurityToken;
import r01f.oids.SecurityOIDs.SecurityPrincipalOID;
