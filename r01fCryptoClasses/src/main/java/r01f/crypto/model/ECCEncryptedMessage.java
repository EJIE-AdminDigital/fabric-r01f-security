package r01f.crypto.model;

import lombok.Getter;
import lombok.experimental.Accessors;

@Accessors(prefix="_")
public class ECCEncryptedMessage
	 extends EncryptedMessage {
/////////////////////////////////////////////////////////////////////////////////////////
//	FIELDS
/////////////////////////////////////////////////////////////////////////////////////////
	@Getter private final byte[] _eccData;
/////////////////////////////////////////////////////////////////////////////////////////
//	CONSTRUCTOR
/////////////////////////////////////////////////////////////////////////////////////////
	public ECCEncryptedMessage(final byte[] messageData, final byte[] eccData) {
		super(messageData);
		_eccData = eccData;
	}
}
