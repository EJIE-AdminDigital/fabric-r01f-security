package r01f.security.saml.api;

import org.opensaml.saml.saml2.core.Status;
import org.opensaml.saml.saml2.core.StatusCode;
import org.opensaml.saml.saml2.core.StatusDetail;
import org.opensaml.saml.saml2.core.StatusMessage;


public class SAMLLogoutResponse {
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	private final Status _status;
/////////////////////////////////////////////////////////////////////////////////////////
//	CONSTRUCTOR
/////////////////////////////////////////////////////////////////////////////////////////
	public SAMLLogoutResponse(final Status status) {
		_status = status;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	VALID
/////////////////////////////////////////////////////////////////////////////////////////
	public boolean isValid() {
		return StatusCode.SUCCESS.equals(_status.getStatusCode().getValue());
	}
	public boolean isNotValid() {
		return !this.isValid();
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	GET
/////////////////////////////////////////////////////////////////////////////////////////	
	public String getStatusCode() {
		return _status.getStatusCode().getValue();
	}
	public String getMessage() {
		StatusMessage statusMessage = _status.getStatusMessage();
		return statusMessage == null ? "none" : statusMessage.getMessage();
	}
	public String getDetails() {
		StatusDetail statusDetail = _status.getStatusDetail();
		return statusDetail == null ? "none" : statusDetail.toString();
	}
}
