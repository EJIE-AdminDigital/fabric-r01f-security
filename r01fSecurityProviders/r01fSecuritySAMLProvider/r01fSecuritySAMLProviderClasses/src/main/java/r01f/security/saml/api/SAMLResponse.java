package r01f.security.saml.api;

import org.opensaml.saml.saml2.core.Assertion;

import lombok.Getter;
import lombok.experimental.Accessors;
import r01f.security.saml.api.SAMLIDs.SAMLIssuerID;

@Accessors(prefix="_")
public class SAMLResponse {
/////////////////////////////////////////////////////////////////////////////////////////
//	FIELDS
/////////////////////////////////////////////////////////////////////////////////////////
	@Getter private final SAMLIssuerID _issuerId;
	@Getter private final Assertion _assertion;
/////////////////////////////////////////////////////////////////////////////////////////
//	CONSTRUCTOR
/////////////////////////////////////////////////////////////////////////////////////////
	public SAMLResponse(final SAMLIssuerID issuerId,
						final Assertion assertion) {
		_issuerId = issuerId;
		_assertion = assertion;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	public String getNameID() {
		return _assertion.getSubject()
						 .getNameID()
						 .getValue();
	}
}
