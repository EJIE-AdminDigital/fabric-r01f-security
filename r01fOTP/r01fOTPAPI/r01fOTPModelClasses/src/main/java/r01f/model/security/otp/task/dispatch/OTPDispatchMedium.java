package r01f.model.security.otp.task.dispatch;

import lombok.Getter;
import lombok.RequiredArgsConstructor;
import lombok.experimental.Accessors;
import r01f.enums.EnumWithCode;

@Accessors(prefix="_")
@RequiredArgsConstructor
public enum OTPDispatchMedium
 implements EnumWithCode<String,OTPDispatchMedium> {
/////////////////////////////////////////////////////////////////////////////////////////
//
/////////////////////////////////////////////////////////////////////////////////////////
	EMAIL("email"),
	SMS("sms");
/////////////////////////////////////////////////////////////////////////////////////////
//
/////////////////////////////////////////////////////////////////////////////////////////
	@Getter private final String _code;
	@Getter private final Class<String> _codeType = String.class;

/////////////////////////////////////////////////////////////////////////////////////////
//  WRAPPER
/////////////////////////////////////////////////////////////////////////////////////////
	public static final OTPDispatchMedium fromString(final String code) {
		return EnumWithCode.fromCode(code,OTPDispatchMedium.class)
						   .orElseThrow(() -> new IllegalArgumentException("no " + OTPDispatchMedium.class + " element with code=" + code));
	}
}